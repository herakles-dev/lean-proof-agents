#!/usr/bin/env bash
# witness-to-lean.sh — materialize a Lean CERTIFICATE challenge from a solver search result.
#
# The witness→Lean bridge (the "moat"): turns a `.search/<id>/witness.json` (from solve.sh) into a
# kernel-checked challenge module that cites a `MathProof.Certify` lemma — so a solver result stays
# Lean-verified. v1 supports the `forall-bounded-nat` shape (a bounded "no witness in [lo,N)" result
# over ℕ, e.g. Erdős #647): a `decide +kernel` core bridged by `Certify.Sup.lt_ciSup_of_exists_range`.
# Other shapes (exists-nat / graph-counterexample / finset-witness) are TODO (Wave D).
#
#   scripts/witness-to-lean.sh --name "<title>" --shape forall-bounded-nat \
#       --witness .search/<id>/witness.json --c "<c(n)>" --f "<f(m)>" --sup-body "<⨆ body, m:Fin n>" \
#       --lo <LO> --certified-n <N> [--open "<namespaces>"] [--dry-run [--ns <Namespace>]]
#
# --c / --f : ℕ exprs so the decidable core is  `∃ m ∈ Finset.range n, <c> < <f>`  (m,n free ℕ vars).
# --sup-body: the ⨆-summand with `m : Fin n` (usually <f> with m cast, e.g. "((m:ℕ) + σ 0 m)").
# --certified-n: the kernel-certified upper bound (keep small — the `decide +kernel` ceiling is ~100–200).
# --dry-run : print the module to stdout (use --ns to fix the namespace) instead of scaffolding a challenge.
# Non-dry-run: runs new-challenge.sh, writes the module + an honest-partial doc, builds, check-proof.sh.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

case "${1:-}" in
  ""|-h|--help) awk 'NR==1{next} /^#/{sub(/^# ?/,"");print;next} /^[[:space:]]*$/{next} {exit}' "$0"; exit 0 ;;
esac

NAME=""; SHAPE=""; WIT=""; C=""; F=""; SUPBODY=""; LO=""; CN=""; OPENS="ArithmeticFunction ArithmeticFunction.sigma"
DRY=0; NS=""
while [[ $# -gt 0 ]]; do
  case "$1" in
    --name) NAME="$2"; shift 2 ;;
    --shape) SHAPE="$2"; shift 2 ;;
    --witness) WIT="$2"; shift 2 ;;
    --c) C="$2"; shift 2 ;;
    --f) F="$2"; shift 2 ;;
    --sup-body) SUPBODY="$2"; shift 2 ;;
    --lo) LO="$2"; shift 2 ;;
    --certified-n) CN="$2"; shift 2 ;;
    --open) OPENS="$2"; shift 2 ;;
    --dry-run) DRY=1; shift ;;
    --ns) NS="$2"; shift 2 ;;
    *) echo "unknown arg: $1" >&2; exit 1 ;;
  esac
done

[[ "$SHAPE" == "forall-bounded-nat" ]] || { echo "❌ v1 supports only --shape forall-bounded-nat (got: '$SHAPE')" >&2; exit 1; }
[[ -n "$C" && -n "$F" && -n "$SUPBODY" && -n "$LO" && -n "$CN" ]] || { echo "❌ need --c --f --sup-body --lo --certified-n" >&2; exit 1; }
# ANTI-VACUITY GATE (the whole point of the moat): if lo ≥ certified-n then `Finset.Ico lo n` is
# EMPTY, so the generated `∀ n ∈ Finset.Ico lo n, …` theorems are VACUOUSLY true — decide+kernel
# passes and check-proof.sh (sorry/axiom-only) reports SOLVED, while the doc-comment falsely claims
# "Certified over [lo, n)". Refuse to emit a certificate that certifies nothing over an empty range.
[[ "$LO" =~ ^[0-9]+$ && "$CN" =~ ^[0-9]+$ ]] || { echo "❌ --lo ($LO) and --certified-n ($CN) must be non-negative integers" >&2; exit 1; }
(( LO < CN )) || { echo "❌ --lo ($LO) must be < --certified-n ($CN): Finset.Ico $LO $CN is EMPTY → a vacuously-true certificate that proves nothing. Refusing." >&2; exit 1; }

# Searched range (for the honesty note), best-effort from witness.json.
SEARCHED="(searched range unknown)"
if [[ -n "$WIT" && -f "$WIT" ]]; then
  SEARCHED="$(python3 -c 'import json,sys
j=json.load(open(sys.argv[1]))
r=j.get("range",["?","?"]); nw=len(j.get("witnesses",[])); nt=j.get("notes",{})
print(f"sweep searched [{r[0]},{r[1]}): {nw} witness(es); "+", ".join(f"{k}={v}" for k,v in nt.items() if k in ("min_excess","argmin_n")))' "$WIT" 2>/dev/null || echo "(searched range unknown)")"
fi

gen_module() {  # uses: NS OPENS LO CN C F SUPBODY SEARCHED
  cat <<EOF
import MathProof.Basic
import MathProof.Certify

set_option autoImplicit false

open ${OPENS}

/-!
# ${NS} — bounded no-witness certificate (generated by witness-to-lean.sh)

A \`decide +kernel\` core bridged to the ⨆-form via \`Certify.Sup.lt_ciSup_of_exists_range\` (the
witness→Lean moat). **Certified** over \`[${LO}, ${CN})\`; ${SEARCHED}. The searched range is
evidence, the certified range is kernel-checked — this is an honest PARTIAL result, **not** a
prize/full-resolution claim.
-/

namespace ${NS}

/-- Decidable core (\`decide +kernel\`): for every \`n ∈ [${LO},${CN})\`, some \`m < n\` has \`${C} < ${F}\`. -/
theorem no_witness_core :
    ∀ n ∈ Finset.Ico ${LO} ${CN}, ∃ m ∈ Finset.range n, ${C} < ${F} := by
  decide +kernel

/-- Bounded no-witness certificate: over \`[${LO},${CN})\`, \`${C} < ⨆ …\` — no witness there. -/
theorem no_witness_below :
    ∀ n ∈ Finset.Ico ${LO} ${CN}, ${C} < ⨆ m : Fin n, ${SUPBODY} := by
  intro n hn
  exact MathProof.Certify.Sup.lt_ciSup_of_exists_range (no_witness_core n hn)

end ${NS}
EOF
}

if [[ "$DRY" == 1 ]]; then
  NS="${NS:-Generated.WitnessCertificate}"
  gen_module
  exit 0
fi

# --- real materialization ---
[[ -n "$NAME" ]] || { echo "❌ --name required (unless --dry-run)" >&2; exit 1; }
created="$(scripts/new-challenge.sh "$NAME")" || { echo "❌ new-challenge.sh failed" >&2; exit 1; }
modfile="$(echo "$created" | grep -oE 'MathProof/Challenges/C[0-9]{4}[A-Za-z0-9]+\.lean' | head -1)"
[[ -n "$modfile" ]] || { echo "❌ could not parse created module path" >&2; echo "$created" >&2; exit 1; }
mod="$(basename "$modfile" .lean)"
NS="MathProof.Challenges.${mod}"
gen_module > "$ROOT/$modfile"
echo "→ wrote $modfile (namespace $NS)" >&2
echo "→ building + certifying…" >&2
lake build "MathProof.Challenges.${mod}" >&2
scripts/check-proof.sh "$mod" --all
echo "✔ certificate materialized: $modfile" >&2
