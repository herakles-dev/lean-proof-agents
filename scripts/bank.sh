#!/usr/bin/env bash
# bank.sh — shared lemma-bank for PARALLEL / ASYNC swarm proving (shared-blackboard topology).
#
# Multiple provers attack the INDEPENDENT LEAVES of one proof at once. Each prover owns its own
# file (no edit contention) and writes a self-contained, PUBLIC, proven lemma into the bank as its
# own importable module under MathProof/Bank/<Attempt>/. A per-attempt aggregator
# MathProof/Bank/<Attempt>.lean imports every leaf added SO FAR — that is the shared blackboard:
# a prover dispatched on a later leaf imports it to build on already-proven results, and it grows
# asynchronously as each leaf lands. The orchestrator ASSEMBLES the bank into one self-contained
# challenge module and kernel-gates it (check-proof.sh / verify-all.sh) — the swarm never weakens
# the trusted gate.
#
#   scripts/bank.sh init      <Attempt>                     # create the bank dir + empty blackboard
#   scripts/bank.sh add       <Attempt> <LeafName> <file>   # publish a proven leaf; regen blackboard
#   scripts/bank.sh blackboard <Attempt>                    # print the import line provers should add
#   scripts/bank.sh list      <Attempt>                     # list published leaves
#   scripts/bank.sh verify    <Attempt>                     # build blackboard + no-sorry/axiom gate each leaf
#   scripts/bank.sh race      <Attempt> <LeafName> <c1> ... # Phase ② best-of-N: first kernel-clean candidate wins
#   scripts/bank.sh assemble  <Attempt> <TargetModule>      # inline leaves (topo order) → MathProof/Challenges/<Target>.lean
#   scripts/bank.sh clean     <Attempt>                     # remove the bank dir + aggregator
#   scripts/bank.sh selftest                                # adversarial regression for assemble+race (no <Attempt>)
#
# Conventions a leaf file MUST follow (so the blackboard + assembly work):
#   * `import MathProof.Basic` (+ one `import MathProof.Bank.<Attempt>.<Dep>` per dependency leaf —
#     import the SPECIFIC dep leaves, NEVER the `<Attempt>` aggregator: a leaf that imported the
#     aggregator would form a build cycle the moment it is itself added to that aggregator.)
#   * `namespace MathProof.Bank.<Attempt>` ... `end MathProof.Bank.<Attempt>`
#   * lemmas that OTHER leaves depend on must be PUBLIC (Lean `private` is module-scoped and would
#     be invisible across bank modules). Cross-leaf references use BARE names (same namespace).
# Bank lives INSIDE the package (so leaves are importable during the parallel phase) but is gitignored.
# Requires: bash and lake/lean (elan), mktemp, grep, sed.
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"
SELF="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/$(basename "${BASH_SOURCE[0]}")"  # abs path, for self-invocation (selftest)
. "$HOME/.elan/env" 2>/dev/null || export PATH="$HOME/.elan/bin:$PATH"

BANK_DIR_REL="MathProof/Bank"
cmd="${1:-}"; att="${2:-}"

die() { echo "$1" >&2; exit 2; }
[[ -z "$cmd" ]] && die "usage: bank.sh {init|add|blackboard|list|verify|assemble|clean|selftest} <Attempt> [...]"
# `selftest` takes no <Attempt> (it drives its own throwaway attempt); everything else requires one.
if [[ "$cmd" != "selftest" ]]; then
  [[ -z "$att" ]] && die "missing <Attempt> (a CamelCase id, e.g. C0046Foo)"
  [[ "$att" =~ ^[A-Za-z][A-Za-z0-9]*$ ]] || die "Attempt must be a single CamelCase identifier (no dots/spaces): got '$att'"
fi

ns="MathProof.Bank.${att}"
leafdir="${BANK_DIR_REL}/${att}"
agg="${BANK_DIR_REL}/${att}.lean"

# Regenerate the blackboard aggregator from whatever leaves currently exist.
regen_blackboard() {
  {
    echo "/- AUTO-GENERATED blackboard for swarm attempt ${att}. Do not edit by hand."
    echo "   Regenerated by scripts/bank.sh; imports every published leaf. -/"
    if compgen -G "${leafdir}/*.lean" > /dev/null; then
      for f in "${leafdir}"/*.lean; do
        base="$(basename "$f" .lean)"
        echo "import ${ns}.${base}"
      done
    fi
  } > "$agg"
}

# Emit leaf basenames in dependency (topological) order: a leaf's in-bank deps — encoded as its
# `import ${ns}.<Dep>` lines — are inlined BEFORE it, because Lean has no forward references within
# a single file. Without this, `assemble`'s alphabetical glob can place a combiner ahead of its
# deps (e.g. `Combiner`/`DvdThirty` sort before `DvdTwo`) → "unknown identifier" after inlining.
# Kahn's algorithm; alphabetical tie-break for deterministic output; aborts on an import cycle.
topo_order_leaves() {
  local nsre; nsre="$(printf '%s' "$ns" | sed 's/\./\\./g')"
  local -a all=(); local f base d
  for f in "${leafdir}"/*.lean; do all+=("$(basename "$f" .lean)"); done
  declare -A deps; declare -A done_map
  for base in "${all[@]}"; do
    # NB: script runs under `set -euo pipefail`. A base leaf with NO in-bank import makes `grep`
    # exit 1, which pipefail propagates and `set -e` would treat as fatal — falsely aborting the
    # sort on every DAG that has a dependency-free leaf (i.e. always). Trailing `|| true` keeps the
    # substitution exit 0 so a genuine empty dep-set is just an empty string.
    deps[$base]="$(grep -oE "^import ${nsre}\.[A-Za-z0-9]+" "${leafdir}/${base}.lean" 2>/dev/null \
                   | sed -E "s/^import ${nsre}\.//" | tr '\n' ' ' || true)"
  done
  local n=${#all[@]} count=0 progress ready
  while [[ $count -lt $n ]]; do
    progress=0
    while IFS= read -r base; do
      [[ -n "${done_map[$base]:-}" ]] && continue
      ready=1
      for d in ${deps[$base]}; do
        # only gate on deps that are themselves leaves in THIS bank
        if [[ " ${all[*]} " == *" $d "* && -z "${done_map[$d]:-}" ]]; then ready=0; break; fi
      done
      if [[ $ready -eq 1 ]]; then echo "$base"; done_map[$base]=1; count=$((count+1)); progress=1; fi
    done < <(printf '%s\n' "${all[@]}" | sort)
    [[ $progress -eq 0 ]] && { echo "assemble: import cycle among bank leaves — cannot order" >&2; return 1; }
  done
  # Explicit success: the terminating `while [[ $count -lt $n ]]` test exits 1 on normal completion,
  # which would otherwise become the function's return status and be misread as a cycle failure.
  return 0
}

case "$cmd" in
  init)
    mkdir -p "$leafdir"
    regen_blackboard
    grep -qxF "MathProof/Bank/" .gitignore 2>/dev/null || echo "MathProof/Bank/" >> .gitignore
    echo "✅ bank init: ${leafdir}/ + ${agg} (aggregator, for verify). gitignored. Leaf namespace: ${ns}"
    echo "   Leaves import: import MathProof.Basic  +  one 'import ${ns}.<Dep>' per dependency leaf"
    echo "   (import SPECIFIC dep leaves, NOT the ${att} aggregator — that would cycle)."
    ;;

  add)
    leaf="${3:-}"; src="${4:-}"
    [[ -z "$leaf" || -z "$src" ]] && die "usage: bank.sh add <Attempt> <LeafName> <file>"
    [[ "$leaf" =~ ^[A-Za-z][A-Za-z0-9]*$ ]] || die "LeafName must be a CamelCase identifier: '$leaf'"
    [[ -f "$src" ]] || die "not found: $src"
    [[ -d "$leafdir" ]] || die "bank not initialized — run: bank.sh init ${att}"
    # sanity: reject a leaf that still has a sorry
    if grep -qiE "\bsorry\b|native_decide" "$src"; then
      die "refusing to add '${src}': contains sorry/native_decide (leaves must be complete + kernel-clean)"
    fi
    dest="${leafdir}/${leaf}.lean"
    # A leaf-prover writes its file straight INTO the bank leafdir (per the /swarm contract), so
    # `add` is frequently called with src == dest. Plain `cp a a` errors ("are the same file") and,
    # under `set -e`, aborts before the blackboard is regenerated. Skip the copy in that case;
    # `add` then just (re-)publishes the in-place leaf and regenerates the blackboard idempotently.
    if [[ ! "$src" -ef "$dest" ]]; then
      cp "$src" "$dest"
    fi
    regen_blackboard
    echo "✅ added leaf ${leaf} → ${leafdir}/${leaf}.lean; blackboard regenerated ($(compgen -G "${leafdir}/*.lean" | wc -l) leaves)"
    ;;

  blackboard)
    # Print the per-leaf import lines currently ON the board (what a new leaf may build on).
    # A dependent leaf imports the SPECIFIC lines it needs — never the aggregator (cycle).
    if compgen -G "${leafdir}/*.lean" > /dev/null; then
      for f in "${leafdir}"/*.lean; do echo "import ${ns}.$(basename "$f" .lean)"; done
    else
      echo "-- (blackboard empty)"
    fi
    ;;

  list)
    if compgen -G "${leafdir}/*.lean" > /dev/null; then
      for f in "${leafdir}"/*.lean; do echo "  $(basename "$f" .lean)  ($f)"; done
    else
      echo "  (no leaves yet)"
    fi
    ;;

  verify)
    [[ -d "$leafdir" ]] || die "bank not initialized: ${att}"
    echo "Building blackboard ${ns} ..."
    lake build "${ns}" 2>&1 | grep -viE 'LEAN_PATH|^trace:' | grep -iE 'sorry|error|Built|completed' || true
    echo "--- per-leaf no-sorry + axiom gate ---"
    local_fail=0
    vlog="$(mktemp)"; trap 'rm -f "$vlog"' EXIT
    for f in "${leafdir}"/*.lean; do
      base="$(basename "$f" .lean)"
      if scripts/check-proof.sh "${ns}.${base}" --all >"$vlog" 2>&1; then
        echo "  ✅ ${base}"
      else
        echo "  ❌ ${base}"; tail -3 "$vlog"; local_fail=1
      fi
    done
    rm -f "$vlog"
    [[ $local_fail -eq 0 ]] && echo "✅ all leaves clean" || { echo "❌ some leaves failed"; exit 1; }
    ;;

  assemble)
    target="${3:-}"
    [[ -z "$target" ]] && die "usage: bank.sh assemble <Attempt> <TargetModule> (e.g. C0046Foo)"
    [[ -d "$leafdir" ]] || die "bank not initialized: ${att}"
    compgen -G "${leafdir}/*.lean" > /dev/null || die "no leaves to assemble"
    out="MathProof/Challenges/${target}.lean"
    tns="MathProof.Challenges.${target}"
    # collect unioned `open` lines across leaves (dedup), strip import/namespace/end/set_option/open.
    opens="$(grep -hE '^open ' "${leafdir}"/*.lean 2>/dev/null | sort -u || true)"
    {
      echo "import MathProof.Basic"
      echo ""
      echo "set_option autoImplicit false"
      echo ""
      [[ -n "$opens" ]] && { echo "$opens"; echo ""; }
      echo "/-! Assembled by scripts/bank.sh from swarm bank ${att}."
      echo "    Self-contained: bank cross-references were bare names in a shared namespace, so"
      echo "    inlining them under one namespace preserves resolution. MUST pass check-proof.sh. -/"
      echo ""
      echo "namespace ${tns}"
      # Inline leaves in DEPENDENCY (topological) order — Lean has no forward references within a
      # single file, so a combiner must follow its deps. topo_order_leaves encodes the F2 fix;
      # the earlier alphabetical glob only worked when names happened to sort dep-before-combiner
      # (e.g. C0046's "Main" > "Dvd*"). Fail loudly on an import cycle rather than emit a broken file.
      if ! _assemble_order="$(topo_order_leaves)"; then
        die "assemble: could not topologically order bank leaves (import cycle among leaves?)"
      fi
      while IFS= read -r base; do
        [[ -z "$base" ]] && continue
        echo ""
        echo "-- ── leaf: ${base} ──"
        grep -vE '^(import |namespace |end |set_option autoImplicit|open )' "${leafdir}/${base}.lean"
      done <<< "$_assemble_order"
      echo ""
      echo "end ${tns}"
    } > "$out"
    echo "✅ assembled ${out} (namespace ${tns})"
    echo "   NEXT: lake build + scripts/check-proof.sh ${target} --all  (the real gate)"
    ;;

  clean)
    rm -rf "$leafdir" "$agg"
    echo "🧹 removed bank ${att}"
    ;;

  race)
    # Phase ② best-of-N crux racing ADJUDICATOR. Given N candidate leaf files (each a COMPLETE,
    # kernel-clean bank leaf proving the SAME crux lemma via a different strategy — written by
    # racers to their own paths, NOT into the leaf dir), install each in turn as the canonical
    # leaf, gate it (build + no-sorry + trusted axioms via check-proof --all), and keep the FIRST
    # that passes. The parallel dispatch + loser cancellation is the orchestrator's live job (see
    # the /swarm skill); this subcommand makes "first kernel-clean wins" deterministic + replayable.
    #   scripts/bank.sh race <Attempt> <LeafName> <cand1.lean> [cand2.lean ...]
    leaf="${3:-}"
    [[ -z "$leaf" ]] && die "usage: bank.sh race <Attempt> <LeafName> <cand1.lean> [cand2 ...]"
    [[ "$leaf" =~ ^[A-Za-z][A-Za-z0-9]*$ ]] || die "LeafName must be a CamelCase identifier: '$leaf'"
    [[ -d "$leafdir" ]] || die "bank not initialized: ${att}"
    shift 3 2>/dev/null || die "usage: bank.sh race <Attempt> <LeafName> <cand1.lean> [cand2 ...]"
    cands=("$@")
    [[ ${#cands[@]} -ge 1 ]] || die "race needs ≥1 candidate file"
    dest="${leafdir}/${leaf}.lean"
    winner=""; i=0
    rlog="$(mktemp)"; trap 'rm -f "$rlog"' EXIT
    for cand in "${cands[@]}"; do
      i=$((i+1))
      [[ -f "$cand" ]] || { echo "  ⚠ cand ${i}: not found ($cand) — skip"; continue; }
      if grep -qiE "\bsorry\b|native_decide" "$cand"; then
        echo "  ❌ cand ${i} ($(basename "$cand")): contains sorry/native_decide — skip"; continue
      fi
      cp "$cand" "$dest"
      regen_blackboard
      if scripts/check-proof.sh "${ns}.${leaf}" --all >"$rlog" 2>&1; then
        echo "  ✅ cand ${i} ($(basename "$cand")): kernel-clean → WINNER"
        winner="$cand"; break
      else
        echo "  ❌ cand ${i} ($(basename "$cand")): failed the gate"; tail -2 "$rlog"
      fi
    done
    rm -f "$rlog"
    if [[ -n "$winner" ]]; then
      regen_blackboard
      echo "🏁 race winner → ${dest} (leaf ${leaf}); blackboard regenerated. Cancel the other racers."
    else
      rm -f "$dest"; regen_blackboard
      echo "🏁 no candidate passed the kernel gate — crux still OPEN (escalate / re-strategize)"; exit 1
    fi
    ;;

  selftest)
    # Permanent ADVERSARIAL regression test for `assemble` — the F1/F2 happy-path-masking lesson:
    # both prior bank bugs shipped because they were validated on convenient inputs (separate src
    # files masked the src==dest contract; a combiner named "Main" sorted after its "Dvd*" deps so
    # the alphabetical glob never exercised the topo path). This drives the real subcommands via a
    # throwaway attempt and asserts the three cases that actually break:
    #   A) a combiner whose name sorts BEFORE its dep + a dep-free leaf  → assemble must emit
    #      dep-first AND the module must compile (guards the topo wiring, the pipefail-safe deps
    #      grep, and the explicit `return 0`);
    #   C) a genuine import cycle → assemble must be REJECTED (non-zero).
    st="BankSelfTest"; stdir="${BANK_DIR_REL}/${st}"; stns="MathProof.Bank.${st}"
    stout_mod="ZZBankSelfTestOut"; stout="MathProof/Challenges/${stout_mod}.lean"
    _st_cleanup() { "$SELF" clean "$st" >/dev/null 2>&1 || true; rm -f "$stout" "${BANK_DIR_REL}"/.selftest_cand_*.lean; }
    trap _st_cleanup EXIT
    _st_cleanup                       # start from a clean slate
    fail=0
    "$SELF" init "$st" >/dev/null
    # ── Case A: adversarial naming (combiner "Aaa" < dep "Zed") + dep-free leaf ──
    cat > "${stdir}/Zed.lean" <<EOF
import MathProof.Basic
namespace ${stns}
theorem zed_fact : 2 + 2 = 4 := by norm_num
end ${stns}
EOF
    cat > "${stdir}/Aaa.lean" <<EOF
import MathProof.Basic
import ${stns}.Zed
namespace ${stns}
theorem aaa_combiner : (2 + 2 = 4) ∧ True := ⟨zed_fact, trivial⟩
end ${stns}
EOF
    "$SELF" add "$st" Zed "${stdir}/Zed.lean" >/dev/null
    "$SELF" add "$st" Aaa "${stdir}/Aaa.lean" >/dev/null
    if "$SELF" assemble "$st" "$stout_mod" >/dev/null 2>&1; then
      order="$(grep -oE 'leaf: (Zed|Aaa)' "$stout" | sed 's/leaf: //' | tr '\n' ' ')"
      if [[ "$order" == "Zed Aaa "* ]]; then echo "  ✅ A/topo: dep 'Zed' inlined before combiner 'Aaa'"
      else echo "  ❌ A/topo: expected 'Zed' before 'Aaa', got: [$order]"; fail=1; fi
      if lake build "MathProof.Challenges.${stout_mod}" >/dev/null 2>&1; then echo "  ✅ A/build: assembled module compiles"
      else echo "  ❌ A/build: assembled module failed to compile"; fail=1; fi
    else
      echo "  ❌ A/assemble: FAILED on a valid DAG (pipefail or return-0 regression)"; fail=1
    fi
    # ── Case C: genuine import cycle must be rejected ──
    rm -f "${stdir}"/*.lean "$stout"
    cat > "${stdir}/Cyc1.lean" <<EOF
import MathProof.Basic
import ${stns}.Cyc2
namespace ${stns}
theorem cyc1 : True := trivial
end ${stns}
EOF
    cat > "${stdir}/Cyc2.lean" <<EOF
import MathProof.Basic
import ${stns}.Cyc1
namespace ${stns}
theorem cyc2 : True := trivial
end ${stns}
EOF
    "$SELF" add "$st" Cyc1 "${stdir}/Cyc1.lean" >/dev/null
    "$SELF" add "$st" Cyc2 "${stdir}/Cyc2.lean" >/dev/null
    if "$SELF" assemble "$st" "$stout_mod" >/dev/null 2>&1; then
      echo "  ❌ C/cycle: assemble SUCCEEDED on a cyclic DAG (must reject)"; fail=1
    else
      echo "  ✅ C/cycle: assemble correctly rejected the import cycle"
    fi
    # ── Case R: best-of-N race — a sorry candidate is skipped, a clean one wins; all-sorry fails ──
    rm -f "${stdir}"/*.lean "$stout"
    cat > "${BANK_DIR_REL}/.selftest_cand_sorry.lean" <<EOF
import MathProof.Basic
namespace ${stns}
theorem crux_ok : 1 + 1 = 2 := by sorry
end ${stns}
EOF
    cat > "${BANK_DIR_REL}/.selftest_cand_clean.lean" <<EOF
import MathProof.Basic
namespace ${stns}
theorem crux_ok : 1 + 1 = 2 := by norm_num
end ${stns}
EOF
    if "$SELF" race "$st" Crux "${BANK_DIR_REL}/.selftest_cand_sorry.lean" "${BANK_DIR_REL}/.selftest_cand_clean.lean" >/dev/null 2>&1; then
      if [[ -f "${stdir}/Crux.lean" ]] && ! grep -qiE "\bsorry\b" "${stdir}/Crux.lean"; then
        echo "  ✅ R/race: skipped the sorry candidate, installed the clean winner"
      else echo "  ❌ R/race: winner file missing or still contains sorry"; fail=1; fi
    else
      echo "  ❌ R/race: reported no winner though a clean candidate existed"; fail=1
    fi
    if "$SELF" race "$st" Crux2 "${BANK_DIR_REL}/.selftest_cand_sorry.lean" >/dev/null 2>&1; then
      echo "  ❌ R/race-allfail: returned success with only a sorry candidate"; fail=1
    else
      echo "  ✅ R/race-allfail: correctly reported no winner (exit≠0)"
    fi
    [[ $fail -eq 0 ]] && echo "✅ bank.sh selftest PASSED" || { echo "❌ bank.sh selftest FAILED"; exit 1; }
    ;;

  *) die "unknown command: $cmd" ;;
esac
